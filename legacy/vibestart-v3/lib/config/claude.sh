- `/grace-verification` — Define test strategy
- `/grace-status` — Check project health

## Integration Status

CONTEXT_EOF
    
    # Add integration status
    if [[ "$conport_mode" != "skip" ]]; then
        echo "- **ConPort**: $conport_mode mode (project memory)" >> "$CONTEXT_FILE"
    fi
    
    if [[ "$entire_mode" == "enabled" ]]; then
        echo "- **Entire.io**: enabled (library documentation)" >> "$CONTEXT_FILE"
    fi
    
    cat >> "$CONTEXT_FILE" << 'CONTEXT_EOF2'

## Standards

This project follows these development standards:

- Architecture: Layer dependencies and boundaries
- Error Handling: Logging and error management
- Git Workflow: Commit format and branching
- Agent Transparency: Action context protocol

## Quick Reference

- **Standards**: .vibestart/src/standards/*/SKILL.md
- **Templates**: .vibestart/src/templates/*.xml.template
- **GRACE Artifacts**: docs/*.xml
- **Marketplace Skills**: ~/.claude/skills/grace/

---

*Generated by vibestart v3.2.0*
CONTEXT_EOF2
    
    ui_success "Created $CONTEXT_FILE"
}

# ═══════════════════════════════════════════════════════════════════════════
# MCP Servers Configuration
# ═══════════════════════════════════════════════════════════════════════════

generate_claude_mcp() {
    local conport_mode="$1"
    local entire_mode="$2"
    
    mkdir -p "$(dirname "$MCP_PATH")"
    
    # Create base MCP config
    json_create "$MCP_PATH"
    
    # Add MCP servers
    local servers='{"mcpServers": {}}'
    echo "$servers" > "$MCP_PATH"
    
    # Add ConPort if enabled
    if [[ "$conport_mode" == "full" ]]; then
        json_set "$MCP_PATH" ".mcpServers.conport" "{
  \"command\": \"$MCP_CONPORT_COMMAND\",
  \"args\": [\"$MCP_CONPORT_ARGS\"]
}"
        ui_info "Added ConPort Full to MCP servers"
    fi
    
    # Add Entire.io if enabled
    if [[ "$entire_mode" == "enabled" ]]; then
        json_set "$MCP_PATH" ".mcpServers.entire" "{
  \"command\": \"$MCP_ENTIRE_COMMAND\",
  \"args\": []
}"
        ui_info "Added Entire.io to MCP servers"
    fi
    
    ui_success "Created $MCP_PATH"
}

# ═══════════════════════════════════════════════════════════════════════════
# Skills Directory Setup
# ═══════════════════════════════════════════════════════════════════════════

generate_claude_skills() {
    mkdir -p "$SKILLS_DIR"
    
    # Create README in skills directory
    cat > "$SKILLS_DIR/README.md" << 'SKILLS_EOF'
# Claude Code Skills

This directory contains custom skills for Claude Code.

## GRACE Shortcuts

GRACE shortcuts are created here when enabled during setup.

## Custom Skills

Add your own skills by creating .md files in this directory.

## Marketplace Skills

Additional skills available from GRACE marketplace:
`~/.claude/skills/grace/`
SKILLS_EOF
    
    ui_success "Created $SKILLS_DIR/"
}

# ═══════════════════════════════════════════════════════════════════════════
# Main Generator
# ═══════════════════════════════════════════════════════════════════════════

# generate_claude_config: Generate Claude context and MCP config
# USAGE: generate_claude_config "conport_mode" "entire_mode" "os"
# RETURNS: 0 = success, 1 = failure
generate_claude_config() {
    local conport_mode="$1"
    local entire_mode="$2"
    local os="$3"

    source "$CLAUDE_LIB_DIR/../profiles/claude.env"
    
    ui_section "Generating Claude Code Configuration"
    
    # Generate context file
    generate_claude_context "$conport_mode" "$entire_mode" "$os"
    
    # Generate MCP servers config
    generate_claude_mcp "$conport_mode" "$entire_mode"
    
    # Create skills directory
    generate_claude_skills
    
    ui_success "Claude Code configuration complete"
    return 0
}

# ═══════════════════════════════════════════════════════════════════════════
# Export Validation
# ═══════════════════════════════════════════════════════════════════════════

declare -f generate_claude_config generate_claude_context generate_claude_mcp generate_claude_skills &>/dev/null || {
    echo "[CONFIG:CLAUDE] Error: Export validation failed" >&2
    exit 1
}
