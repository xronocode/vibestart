#!/bin/bash
# lib/config/claude.sh — Claude Code Configuration Generator
# MODULE_ID: M-CONFIG-CLAUDE
# CONTRACT:
#   PURPOSE: Generate Claude Code configuration files
#   SCOPE: Context file, MCP servers config, skills directory
#   DEPENDS: M-UI, M-JSON
#   EXPORTS:
#     generate_claude_config() — Generate Claude context and MCP config

set -e

# Source dependencies
CLAUDE_CONFIG_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CLAUDE_LIB_DIR="$(cd "$CLAUDE_CONFIG_DIR/.." && pwd)"
# shellcheck source=../ui.sh
source "$CLAUDE_LIB_DIR/ui.sh"
# shellcheck source=../json.sh
source "$CLAUDE_LIB_DIR/json.sh"

# Load profile
source "$CLAUDE_LIB_DIR/../profiles/claude.env"

# ═══════════════════════════════════════════════════════════════════════════
# Context File Generation
# ═══════════════════════════════════════════════════════════════════════════

generate_claude_context() {
    local conport_mode="$1"
    local entire_mode="$2"
    local os="$3"
    
    mkdir -p "$(dirname "$CONTEXT_FILE")"
    
    cat > "$CONTEXT_FILE" << 'CONTEXT_EOF'
# Project Context

This file provides context for Claude Code about the project structure and conventions.

## Project Structure

```
.
├── .claude/              # Claude Code configuration
│   ├── context.md        # This file
│   ├── mcp-servers.json  # MCP server configuration
│   └── skills/           # Custom skills
├── docs/                 # GRACE artifacts
│   ├── development-plan.xml
│   ├── requirements.xml
│   ├── knowledge-graph.xml
│   ├── verification-plan.xml
│   ├── technology.xml
│   └── decisions.xml
├── .vibestart/          # Framework files
│   └── src/
│       ├── standards/   # Development standards
│       ├── templates/   # XML templates
│       └── fragments/   # AGENTS.md components
└── (project files)
```

## GRACE Methodology

This project uses **GRACE** (Guided Rapid Architecture Creation Engine) for contract-driven development.

### Core Principles

1. **Contract-First**: Every module has a MODULE_CONTRACT before implementation
2. **Knowledge Graph**: docs/knowledge-graph.xml tracks dependencies and flows
3. **Verification**: docs/verification-plan.xml defines test strategies
4. **Semantic Markup**: Code includes structured comments for navigation

### Available Commands

