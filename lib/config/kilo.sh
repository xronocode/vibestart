├── docs/                  # GRACE artifacts
│   ├── development-plan.xml
│   ├── requirements.xml
│   ├── knowledge-graph.xml
│   ├── verification-plan.xml
│   ├── technology.xml
│   └── decisions.xml
├── .vibestart/           # Framework files
│   └── src/
│       ├── standards/    # Development standards
│       ├── templates/    # XML templates
│       └── fragments/    # AGENTS.md components
└── (project files)
```

