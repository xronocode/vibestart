# ═══════════════════════════════════════════════════════════════════════════
# MCP Settings Generation
# ═══════════════════════════════════════════════════════════════════════════

generate_kilo_mcp() {
    local conport_mode="$1"
    local entire_mode="$2"
    
    mkdir -p "$(dirname "$MCP_PATH")"
    
    # Create base MCP settings
    json_create "$MCP_PATH"
    
    # Add MCP servers
    local servers='{"mcpServers": {}}'
    echo "$servers" > "$MCP_PATH"
    
    # Add ConPort if enabled
    if [[ "$conport_mode" == "full" ]]; then
        json_set "$MCP_PATH" "conport" "{
  \"command\": \"$MCP_CONPORT_COMMAND\",
  \"args\": [\"$MCP_CONPORT_ARGS\"]
}"
        ui_info "Added ConPort Full to MCP settings"
    fi
    
    # Add Entire.io if enabled
    if [[ "$entire_mode" == "enabled" ]]; then
        json_set "$MCP_PATH" "entire" "{
  \"command\": \"$MCP_ENTIRE_COMMAND\",
  \"args\": []
}"
        ui_info "Added Entire.io to MCP settings"
    fi
    
    ui_success "Created $MCP_PATH"
}

# ═══════════════════════════════════════════════════════════════════════════
# Skills Directory Setup
# ═══════════════════════════════════════════════════════════════════════════

generate_kilo_skills() {
    mkdir -p "$SKILLS_DIR"
    
    # Create README in skills directory
    cat > "$SKILLS_DIR/README.md" << 'SKILLS_EOF'
# Kilo Code Skills

This directory contains custom skills for Kilo Code.

## GRACE Shortcuts

GRACE shortcuts are created here when enabled during setup.

## Custom Skills

Add your own skills by creating .md files in this directory.

## Marketplace Skills

Additional skills available from GRACE marketplace:
`~/.kilocode/skills/grace/`
SKILLS_EOF
    
    ui_success "Created $SKILLS_DIR/"
}

# ═══════════════════════════════════════════════════════════════════════════
# Main Generator
# ═══════════════════════════════════════════════════════════════════════════

# generate_kilo_config: Generate Kilo context and MCP config
# USAGE: generate_kilo_config "conport_mode" "entire_mode" "os"
# RETURNS: 0 = success, 1 = failure
generate_kilo_config() {
    local conport_mode="$1"
    local entire_mode="$2"
    local os="$3"
    
    ui_section "Generating Kilo Code Configuration"
    
    # Generate context file
    generate_kilo_context "$conport_mode" "$entire_mode" "$os"
    
    # Generate MCP settings
    generate_kilo_mcp "$conport_mode" "$entire_mode"
    
    # Create skills directory
    generate_kilo_skills
    
    ui_success "Kilo Code configuration complete"
    return 0
}

# ═══════════════════════════════════════════════════════════════════════════
# Export Validation
# ═══════════════════════════════════════════════════════════════════════════

declare -f generate_kilo_config generate_kilo_context generate_kilo_mcp generate_kilo_skills &>/dev/null || {
    echo "[CONFIG:KILO] Error: Export validation failed" >&2
    exit 1
}
