#!/bin/bash
# lib/config/kilo.sh — Kilo Code Configuration Generator
# MODULE_ID: M-CONFIG-KILO
# CONTRACT:
#   PURPOSE: Generate Kilo Code configuration files
#   SCOPE: Context file, MCP settings, skills directory
#   DEPENDS: M-UI, M-JSON
#   EXPORTS:
#     generate_kilo_config() — Generate Kilo context and MCP config

set -e

# Source dependencies
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LIB_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
# shellcheck source=../ui.sh
source "$LIB_DIR/ui.sh"
# shellcheck source=../json.sh
source "$LIB_DIR/json.sh"

# Load profile
source "$LIB_DIR/../profiles/kilo.env"

# ═══════════════════════════════════════════════════════════════════════════
# Context File Generation
# ═══════════════════════════════════════════════════════════════════════════

generate_kilo_context() {
    local conport_mode="$1"
    local entire_mode="$2"
    local os="$3"
    
    mkdir -p "$(dirname "$CONTEXT_FILE")"
    
    cat > "$CONTEXT_FILE" << 'CONTEXT_EOF'
# Project Context

This file provides context for Kilo Code about the project structure and conventions.

## Project Structure

```
